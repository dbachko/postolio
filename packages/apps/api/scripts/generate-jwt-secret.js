#!/usr/bin/env node

/**
 * Generate a secure JWT secret for development and production
 * Usage: node scripts/generate-jwt-secret.js
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

// Generate a secure random secret
const secret = crypto.randomBytes(32).toString('hex');

console.log('\n🔐 Generated JWT Secret:');
console.log('========================');
console.log(secret);
console.log('========================\n');

// Check if .env file exists
const envPath = path.join(__dirname, '..', '.env');
const envExamplePath = path.join(__dirname, '..', '.env.example');

if (!fs.existsSync(envPath)) {
  console.log('📝 Creating .env file from .env.example...');
  
  if (fs.existsSync(envExamplePath)) {
    const envContent = fs.readFileSync(envExamplePath, 'utf8');
    const updatedContent = envContent.replace(
      /JWT_SECRET=.*/,
      `JWT_SECRET=${secret}`
    );
    fs.writeFileSync(envPath, updatedContent);
    console.log('✅ .env file created with the generated JWT secret!');
  } else {
    // Create a minimal .env file
    const minimalEnv = `# Generated by generate-jwt-secret.js
JWT_SECRET=${secret}
DATABASE_URL=postgresql://postgres:postgres@localhost:5432/postolio
REDIS_URL=redis://localhost:6379
NODE_ENV=development
PORT=3000
`;
    fs.writeFileSync(envPath, minimalEnv);
    console.log('✅ Created minimal .env file with the generated JWT secret!');
  }
} else {
  console.log('⚠️  .env file already exists.');
  console.log('To update your JWT_SECRET, replace the existing value with the secret above.');
  console.log('\nYou can update it manually or run:');
  console.log(`echo "JWT_SECRET=${secret}" >> .env`);
}

console.log('\n📋 Instructions:');
console.log('1. Copy the generated secret above');
console.log('2. Add it to your .env file as: JWT_SECRET=<secret>');
console.log('3. Keep this secret secure and never commit it to version control');
console.log('4. Use different secrets for development and production environments');
console.log('\n✨ For production, consider using AWS Secrets Manager or similar service.');