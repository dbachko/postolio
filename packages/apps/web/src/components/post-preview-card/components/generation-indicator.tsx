import { useMemo } from 'react';
import { Sparkles } from 'lucide-react';
import { useNavigate } from 'react-router-dom';

import type { CalendarItem } from '@/types/calendar';
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from '@/components/ui/tooltip';

function getGenerationMeta(item: CalendarItem): {
  recipeRunId: string | null;
  label: string | null;
} {
  if (item.type === 'placeholder') return { recipeRunId: null, label: null };
  const record = item as unknown as Record<string, unknown>;

  const recipeRunId =
    typeof record.recipeRunId === 'string' && record.recipeRunId.trim().length > 0
      ? record.recipeRunId.trim()
      : null;

  const generatedByRecipe =
    record.generatedByRecipe && typeof record.generatedByRecipe === 'object'
      ? (record.generatedByRecipe as any)
      : null;
  const recipeName =
    typeof generatedByRecipe?.name === 'string' && generatedByRecipe.name.trim().length > 0
      ? generatedByRecipe.name.trim()
      : null;

  return { recipeRunId, label: recipeName };
}

export function GenerationIndicator({ item }: { item: CalendarItem }) {
  const navigate = useNavigate();

  return useMemo(() => {
    const meta = getGenerationMeta(item);
    if (!meta.recipeRunId) return null;

    const tooltip = meta.label ? `Generated by: ${meta.label}` : 'Generated by a recipe';

    return (
      <TooltipProvider>
        <Tooltip>
          <TooltipTrigger asChild>
            <button
              type="button"
              aria-label={tooltip}
              className="border-border text-muted-foreground hover:text-foreground inline-flex h-5 w-5 items-center justify-center rounded-sm border bg-transparent"
              onClick={(e) => {
                e.stopPropagation();
                navigate(`/runs/${encodeURIComponent(meta.recipeRunId!)}`);
              }}
            >
              <Sparkles className="h-3.5 w-3.5" />
            </button>
          </TooltipTrigger>
          <TooltipContent>
            <span className="text-foreground text-[11px] font-medium">{tooltip}</span>
          </TooltipContent>
        </Tooltip>
      </TooltipProvider>
    );
  }, [item, navigate]);
}
