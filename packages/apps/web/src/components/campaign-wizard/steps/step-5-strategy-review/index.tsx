import { useEffect, useMemo, useState } from 'react';
import { Alert, AlertDescription } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { toast } from 'sonner';
import { useCampaignWizard } from '@/hooks/useCampaignWizard';
import { useBrandStore } from '@/stores/brandStore';
import { campaign as campaignApi } from '@/lib/api';
import { WizardHelpDialog } from '@/components/campaign-wizard/shared/wizard-help-dialog';
import { GeneratingStrategyLoader } from '../../shared/generating-strategy-loader';
import { ContentPillarsCard } from './components/content-pillars-card';
import { ForecastCard } from './components/forecast-card';
import { PostingScheduleCard } from './components/posting-schedule-card';
import { TipsCard } from './components/tips-card';
import type {
  PillarDraft,
  SchedulePhase,
  StrategyPredictions,
  StrategyPredictionsMeta,
} from './types';
import { DEFAULT_PILLARS, isDefaultPillars, normalizePillars } from './utils';

export function Step5StrategyReview() {
  const { prevStep, nextStep, contentPillars, updateField } = useCampaignWizard();
  const brand = useBrandStore((s) => s.selectedBrand);
  const wizard = useCampaignWizard();

  const [isGenerating, setIsGenerating] = useState(false);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);
  const [predictions, setPredictions] = useState<StrategyPredictions | null>(
    wizard.strategyPredictions || null
  );
  const [predictionsMeta, setPredictionsMeta] = useState<StrategyPredictionsMeta | null>(
    wizard.strategyPredictionsMeta || null
  );
  const [schedulePhases, setSchedulePhases] = useState<SchedulePhase[]>(
    wizard.strategySchedule?.phases || []
  );
  const [_schedulePostingTime, setSchedulePostingTime] = useState<string | null>(
    wizard.strategySchedule?.postingTime || null
  );
  const [helpOpen, setHelpOpen] = useState(false);
  const [pillars, setPillars] = useState<PillarDraft[]>(
    contentPillars?.pillars?.map((p) => ({ name: p.name, percentage: p.percentage })) ||
      DEFAULT_PILLARS
  );

  const total = useMemo(
    () => pillars.reduce((sum, p) => sum + (Number(p.percentage) || 0), 0),
    [pillars]
  );
  const valid = total === 100 && pillars.every((p) => p.name.trim().length > 0);

  const setName = (index: number, name: string) => {
    setPillars((prev) => prev.map((p, i) => (i === index ? { ...p, name } : p)));
  };

  const setPct = (index: number, pct: number) => {
    const clamped = Math.max(0, Math.min(100, pct));
    setPillars((prev) => prev.map((p, i) => (i === index ? { ...p, percentage: clamped } : p)));
  };

  const addPillar = () =>
    setPillars((prev) => [...prev, { name: `Pillar ${prev.length + 1}`, percentage: 0 }]);

  const removePillar = (index: number) => setPillars((prev) => prev.filter((_, i) => i !== index));

  const onContinue = () => {
    if (!valid) return;
    updateField('contentPillars', { pillars: pillars.map((p) => ({ ...p, themes: [] })) });
    nextStep();
  };

  const canGenerate = useMemo(() => {
    const hasBrand = !!brand;
    const hasTimeline = !!wizard.timeline?.startDate && !!wizard.timeline?.endDate;
    const hasFrequency =
      wizard.frequency === 'daily' ||
      wizard.frequency === 'every2days' ||
      wizard.frequency === '3weekly';
    const hasPostingTime =
      typeof wizard.postingTime === 'string' && /^\d{2}:\d{2}$/.test(wizard.postingTime);
    return hasBrand && hasTimeline && hasFrequency && hasPostingTime;
  }, [
    brand,
    wizard.timeline?.startDate,
    wizard.timeline?.endDate,
    wizard.frequency,
    wizard.postingTime,
  ]);

  useEffect(() => {
    if (
      !hasAutoGenerated &&
      !wizard.strategyPredictions &&
      canGenerate &&
      brand &&
      wizard.timeline
    ) {
      setHasAutoGenerated(true);
      void onGenerate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const onGenerate = async () => {
    if (!canGenerate || !brand || !wizard.timeline) return;

    setIsGenerating(true);
    try {
      const res = await campaignApi.generateCampaignStrategy({
        brandId: brand.id,
        name: wizard.name || 'Campaign',
        goals:
          Array.isArray(wizard.goals) && wizard.goals.length
            ? wizard.goals
            : ['Grow engagement and conversions'],
        campaignType: wizard.campaignType || 'custom',
        timeline: { startDate: wizard.timeline.startDate, endDate: wizard.timeline.endDate },
        themes:
          Array.isArray(wizard.themes) && wizard.themes.length > 0
            ? wizard.themes
            : ['awareness', 'product'],
        style:
          Array.isArray(wizard.style) && wizard.style.length ? wizard.style.join('; ') : 'modern',
        frequency: wizard.frequency as any,
        postingTime: wizard.postingTime,
        promotionDetails: wizard.promotionDetails || undefined,
      });

      if (!res?.success) return;

      const generatedPillars = normalizePillars(
        res.strategy.contentPillars.pillars.map((p: any) => ({
          name: p.name,
          percentage: p.percentage,
        }))
      );

      if (wizard.contentPillars?.pillars?.length || !isDefaultPillars(pillars)) {
        setPillars(normalizePillars(pillars));
        try {
          const merged = (pillars as any[]).map((p: any, i: number) => ({
            name: p.name,
            percentage: p.percentage,
            themes: res.strategy.contentPillars.pillars[i]?.themes || [],
          }));
          updateField('contentPillars', { pillars: merged });
        } catch {
          if (wizard.contentPillars?.pillars?.length) {
            updateField('contentPillars', wizard.contentPillars);
          }
        }
      } else {
        setPillars(generatedPillars);
        updateField('contentPillars', {
          pillars: (res.strategy.contentPillars.pillars as any[]).map((p: any, idx: number) => ({
            name: generatedPillars[idx]?.name ?? p.name,
            percentage: generatedPillars[idx]?.percentage ?? p.percentage,
            themes: p.themes || [],
          })),
        });
      }

      setPredictions(res.strategy.predictions);
      setPredictionsMeta(res.strategy.predictionsMeta || null);
      setSchedulePhases(res.strategy.schedule.phases);
      setSchedulePostingTime(res.strategy.schedule.postingTime);

      updateField('strategyPredictions', res.strategy.predictions);
      updateField('strategyPredictionsMeta', res.strategy.predictionsMeta || null);
      updateField('strategySchedule', {
        phases: res.strategy.schedule.phases as any[],
        postingTime: res.strategy.schedule.postingTime || null,
      } as any);
    } catch (e) {
      console.error('generate strategy failed', e);
      toast.error('Failed to generate strategy. Open Help for guidance.');
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <div className="space-y-6">
      {isGenerating && <GeneratingStrategyLoader />}

      {!isGenerating && predictions && (
        <Alert>
          <AlertDescription>
            Strategy generated! Review the content pillars, forecasts, and schedule below. You can
            edit before continuing.
          </AlertDescription>
        </Alert>
      )}

      <WizardHelpDialog open={helpOpen} onOpenChange={setHelpOpen} currentStep={5} />

      {!isGenerating && (
        <>
          <div className="grid gap-4 md:grid-cols-3">
            <ContentPillarsCard
              pillars={pillars}
              total={total}
              onSetName={setName}
              onSetPercentage={setPct}
              onAddPillar={addPillar}
              onRemovePillar={removePillar}
              onLearnMore={() => setHelpOpen(true)}
            />
            <PostingScheduleCard schedulePhases={schedulePhases} />
            <ForecastCard predictions={predictions} predictionsMeta={predictionsMeta} />
          </div>

          <TipsCard />

          <div className="flex justify-between">
            <Button variant="outline" onClick={prevStep}>
              Back
            </Button>
            <Button onClick={onContinue} disabled={!valid}>
              Continue
            </Button>
          </div>
        </>
      )}
    </div>
  );
}
