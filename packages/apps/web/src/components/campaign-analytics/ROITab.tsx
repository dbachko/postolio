import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { DollarSign, Loader2 } from 'lucide-react';
import { formatNumber } from '@/utils/formatNumber';

interface ROIBreakdown {
  costPerEngagement: string;
  valuePerImpression: string;
  estimatedReach: number;
}

interface ROIData {
  estimatedValue: number;
  engagementValue: number;
  reachValue: number;
  breakdown: ROIBreakdown;
  methodology: string;
}

interface ROITabProps {
  roi: ROIData | undefined;
  isLoading: boolean;
}

export function ROITab({ roi, isLoading }: ROITabProps) {
  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <DollarSign className="h-5 w-5" />
          Return on Investment
        </CardTitle>
        <CardDescription>Estimated value generated by your campaign</CardDescription>
      </CardHeader>
      <CardContent>
        {isLoading ? (
          <div className="flex items-center justify-center py-4">
            <Loader2 className="mr-2 h-5 w-5 animate-spin" />
            Calculating ROI...
          </div>
        ) : !roi ? (
          <p className="text-muted-foreground py-4 text-center">ROI data not available</p>
        ) : (
          <div className="space-y-6">
            <div className="text-center">
              <div className="text-4xl font-bold">${Number(roi.estimatedValue).toFixed(2)}</div>
              <p className="text-muted-foreground text-sm">Estimated campaign value</p>
            </div>

            <div className="grid gap-4 md:grid-cols-2">
              <Card>
                <CardContent className="p-4">
                  <div className="text-center">
                    <p className="text-muted-foreground text-sm">Engagement Value</p>
                    <p className="text-2xl font-bold">${Number(roi.engagementValue).toFixed(2)}</p>
                  </div>
                </CardContent>
              </Card>

              <Card>
                <CardContent className="p-4">
                  <div className="text-center">
                    <p className="text-muted-foreground text-sm">Reach Value</p>
                    <p className="text-2xl font-bold">${Number(roi.reachValue).toFixed(2)}</p>
                  </div>
                </CardContent>
              </Card>
            </div>

            <div className="space-y-2 text-sm">
              <h4 className="font-medium">Calculation Breakdown:</h4>
              <div className="flex justify-between">
                <span>Cost per engagement:</span>
                <span>${roi.breakdown.costPerEngagement}</span>
              </div>
              <div className="flex justify-between">
                <span>Value per impression:</span>
                <span>${roi.breakdown.valuePerImpression}</span>
              </div>
              <div className="flex justify-between">
                <span>Estimated reach:</span>
                <span>{formatNumber(roi.breakdown.estimatedReach)}</span>
              </div>
            </div>

            <div className="text-muted-foreground bg-muted rounded p-3 text-xs">
              <strong>Methodology:</strong> {roi.methodology}
            </div>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
